import uuid
from datetime import datetime
from decimal import Decimal
from typing import Optional, List
from pydantic import BaseModel, Field, ConfigDict


class OrderItemCreate(BaseModel):
    """Line item requested by retailer."""
    product_id: uuid.UUID = Field(..., description="Target Product UUID")
    quantity_cases: int = Field(..., ge=1, description="Quantity in cases (minimum 1)")
    uom_type: str = Field(default="CASE", description="Unit of measure (default: CASE)")


class OrderPreviewRequest(BaseModel):
    """Shopping cart payload to preview pricing, schemes, stock, and credit hold."""
    items: List[OrderItemCreate] = Field(..., min_length=1)


class BenefitDetail(BaseModel):
    """Independent representation of an awarded scheme benefit (discount or free product)."""
    scheme_id: Optional[uuid.UUID] = None
    scheme_name: str
    benefit_type: str  # FREE_GOODS | SLAB_DISCOUNT | FLAT_DISCOUNT
    awarded_product_id: Optional[uuid.UUID] = None
    awarded_sku_code: Optional[str] = None
    awarded_product_name: Optional[str] = None
    awarded_quantity: int = 0
    awarded_uom: str = "CASE"
    discount_amount: Decimal = Decimal("0.00")
    explanation: Optional[str] = None

    model_config = ConfigDict(from_attributes=True)


class OrderPreviewLineResponse(BaseModel):
    """Evaluated cart line item."""
    product_id: uuid.UUID
    sku_code: str
    product_name: str
    requested_qty: int
    available_stock: int
    is_stock_sufficient: bool
    unit_price_excl_gst: Decimal
    price_basis: str
    applied_scheme_name: Optional[str] = None
    discount_amount_excl_gst: Decimal = Decimal("0.00")
    free_goods_qty: int = 0
    free_goods_product_name: Optional[str] = None
    free_goods_sku_code: Optional[str] = None
    line_subtotal_excl_gst: Decimal
    scheme_explanation: Optional[str] = None
    has_scheme_conflict: bool = False
    scheme_conflict_note: Optional[str] = None
    benefits: List[BenefitDetail] = Field(default_factory=list)


class CreditCheckSummary(BaseModel):
    """Evaluation of retailer credit availability against proposed order."""
    credit_limit: Decimal
    current_outstanding: Decimal
    available_credit: Decimal
    proposed_order_amount: Decimal
    is_credit_breached: bool
    will_trigger_credit_hold: bool
    notice: str


class OrderPreviewResponse(BaseModel):
    """Complete cart evaluation prior to submission."""
    lines: List[OrderPreviewLineResponse]
    total_cases: int
    subtotal_excl_gst: Decimal
    total_discount_excl_gst: Decimal
    has_insufficient_stock: bool
    has_scheme_conflicts: bool = False
    credit_check: CreditCheckSummary
    all_free_goods: List[BenefitDetail] = Field(default_factory=list)
    tax_notice: str = "All amounts strictly exclude GST. Final invoice generated by distributor."


class OrderCreateRequest(BaseModel):
    """Order submission payload."""
    items: List[OrderItemCreate] = Field(..., min_length=1)
    delivery_notes: Optional[str] = None
    client_order_id: Optional[str] = Field(default=None, description="Client idempotency key for offline sync")


class RepeatOrderLineDiff(BaseModel):
    """Line-by-line diff comparing historical order line against live catalog state."""
    product_id: uuid.UUID
    sku_code: str
    product_name: str
    original_requested_qty: int
    current_requested_qty: int
    historical_unit_price: Decimal
    current_unit_price: Decimal
    price_changed: bool
    price_diff: Decimal
    price_basis: str
    available_stock: int
    is_stock_sufficient: bool
    is_discontinued: bool
    current_scheme_name: Optional[str] = None
    current_discount_amount: Decimal = Decimal("0.00")
    current_free_qty: int = 0
    current_line_subtotal: Decimal = Decimal("0.00")
    benefits: List[BenefitDetail] = Field(default_factory=list)


class RepeatOrderPreviewResponse(BaseModel):
    """Revalidated preview comparing historical order with real-time stock, pricing, and schemes."""
    original_order_id: uuid.UUID
    original_order_number: str
    lines: List[RepeatOrderLineDiff]
    has_price_changes: bool
    has_unavailable_items: bool
    has_scheme_changes: bool
    subtotal_excl_gst: Decimal
    total_discount_excl_gst: Decimal
    total_cases: int
    credit_check: CreditCheckSummary
    can_proceed: bool
    revalidation_notice: str


class OrderItemResponse(BaseModel):
    """Order line item with immutable snapshot data."""
    id: uuid.UUID
    product_id: uuid.UUID
    ordered_qty: int
    approved_qty: int
    uom_type: str
    applied_scheme_id: Optional[uuid.UUID] = None
    scheme_discount_amount: Decimal
    free_item_qty: int
    line_subtotal_excl_gst: Decimal
    product_name_snapshot: str
    sku_code_snapshot: str
    price_per_unit_snapshot: Decimal
    price_basis_snapshot: str
    scheme_name_snapshot: Optional[str] = None
    discount_percentage_snapshot: Optional[Decimal] = None
    free_product_name_snapshot: Optional[str] = None
    free_sku_code_snapshot: Optional[str] = None
    benefits: List[BenefitDetail] = Field(default_factory=list)

    model_config = ConfigDict(from_attributes=True)


class OrderResponse(BaseModel):
    """Order summary representation."""
    id: uuid.UUID
    order_number: str
    retailer_id: uuid.UUID
    status: str
    subtotal_excl_gst: Decimal
    credit_hold_reason: Optional[str] = None
    desk_notes: Optional[str] = None
    created_at: datetime
    updated_at: datetime
    item_count: int = 0
    retailer_name: Optional[str] = None
    retailer_code: Optional[str] = None

    model_config = ConfigDict(from_attributes=True)


class AuditLogResponse(BaseModel):
    """Audit record for order modifications."""
    id: uuid.UUID
    action: str
    created_at: datetime
    old_values: Optional[dict] = None
    new_values: Optional[dict] = None
    reason: Optional[str] = None

    model_config = ConfigDict(from_attributes=True)


class OrderDetailResponse(OrderResponse):
    """Full order record with items and audit trail."""
    items: List[OrderItemResponse] = []
    audit_logs: List[AuditLogResponse] = []
    retailer_name: Optional[str] = None
    retailer_code: Optional[str] = None
